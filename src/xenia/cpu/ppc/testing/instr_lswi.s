test_lswi_7_bytes:
  #_ MEMORY_IN 10001000 11223344 55667788
  #_ REGISTER_IN r4 0x0000000010001000
  lswi r6, r4, 7
  blr
  #_ REGISTER_OUT r4 0x0000000010001000
  #_ REGISTER_OUT r6 0x0000000011223344
  #_ REGISTER_OUT r7 0x0000000055667700

test_lswi_4_bytes:
  #_ MEMORY_IN 10001000 DEADBEEF
  #_ REGISTER_IN r4 0x0000000010001000
  lswi r6, r4, 4
  blr
  #_ REGISTER_OUT r4 0x0000000010001000
  #_ REGISTER_OUT r6 0x00000000DEADBEEF

test_lswi_1_byte:
  #_ MEMORY_IN 10001000 ABCDEF01
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r6 0xFFFFFFFFFFFFFFFF
  lswi r6, r4, 1
  blr
  #_ REGISTER_OUT r4 0x0000000010001000
  #_ REGISTER_OUT r6 0x00000000AB000000

test_lswi_register_wrap:
  #_ MEMORY_IN 10001000 01020304 05060708
  #_ REGISTER_IN r4 0x0000000010001000
  lswi r31, r4, 8
  blr
  #_ REGISTER_OUT r4 0x0000000010001000
  #_ REGISTER_OUT r31 0x0000000001020304
  #_ REGISTER_OUT r0 0x0000000005060708
