test_stswi_6_bytes:
  #_ MEMORY_IN 10001000 00000000 00000000
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r6 0x00000000AABBCCDD
  #_ REGISTER_IN r7 0x00000000EEFF1122
  stswi r6, r4, 6
  blr
  #_ REGISTER_OUT r4 0x0000000010001000
  #_ MEMORY_OUT 10001000 AABBCCDD EEFF0000

test_stswi_1_byte:
  #_ MEMORY_IN 10001000 00000000
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r6 0x0000000012345678
  stswi r6, r4, 1
  blr
  #_ MEMORY_OUT 10001000 12000000

test_stswi_register_wrap:
  #_ MEMORY_IN 10001000 00000000 00000000
  #_ REGISTER_IN r4 0x0000000010001000
  #_ REGISTER_IN r31 0x0000000001020304
  #_ REGISTER_IN r0 0x0000000005060708
  stswi r31, r4, 8
  blr
  #_ MEMORY_OUT 10001000 01020304 05060708
